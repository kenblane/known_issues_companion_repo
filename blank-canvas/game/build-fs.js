#!/usr/bin/env node
// build-fs.js
//
// Bundles ../homebase and ../graveyard into fs-data.js, so the game's
// fake terminal shows the same files you can browse in this repository.
// Run it again whenever those folders change:  node build-fs.js

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const MOUNTS = { homebase: 'homebase', graveyard: 'graveyard' };
const files = {};

function walk(dir, virtualDir) {
  for (const name of fs.readdirSync(dir).sort()) {
    if (name === 'node_modules') continue;
    const full = path.join(dir, name);
    const virtual = `${virtualDir}/${name}`;
    if (fs.statSync(full).isDirectory()) walk(full, virtual);
    else files[virtual] = fs.readFileSync(full, 'utf8');
  }
}

for (const [folder, mount] of Object.entries(MOUNTS)) {
  walk(path.join(ROOT, folder), `/home/mara/${mount}`);
}

const out = `// GENERATED by build-fs.js. Do not edit by hand.
(function (root) {
  var FILES = ${JSON.stringify(files, null, 1)};
  if (typeof module !== 'undefined' && module.exports) module.exports = FILES;
  else root.HOMEBASE_FS = FILES;
})(this);
`;

fs.writeFileSync(path.join(__dirname, 'fs-data.js'), out);
console.log(`fs-data.js: ${Object.keys(files).length} files`);
